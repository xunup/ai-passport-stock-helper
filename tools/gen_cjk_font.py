#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate the LVGL 9 Chinese bitmap fonts used by the stock ticker.

用法:
  python3 tools/gen_cjk_font.py --font /path/to/SourceHanSansSC-Regular.otf
  python3 tools/gen_cjk_font.py --size 12 --chars 今万亿 --name lv_font_cn_12_pnl

字符集: ASCII + GB2312 一级汉字(3755 字) + 界面所需中文标点;
        --chars 时只生成 ASCII + 指定字符,用于小字号专用字体。
位深:   2bpp(4 级灰度),小字比 1bpp 清晰,比 4bpp 省一半 flash。
输出:   assets/fonts/lv_font_cn_<size>.c(字体进 .rodata/flash,不占 DRAM)

换字体只需改 --font(量产建议使用开源字体,如思源黑体/文泉驿)。
"""
import argparse
import os
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.exit("缺少 Pillow: pip install pillow")

FONT_PATH = os.environ.get("STOCK_FONT_PATH", "")
BPP = 2
OUT_DIR = os.path.join(os.path.dirname(__file__), "../assets/fonts")

# 界面文字会自然包含中文标点；它们不属于 GB2312 汉字区，必须显式加入。
COMMON_SYMBOLS = "，。！？：；、‘’“”（）【】《》…—·￥↑↓"


def gb2312_hanzi():
    """枚举 GB2312 一级汉字(0xB0A1-0xD7FE),与字体覆盖范围一致。"""
    chars = []
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if len(ch) == 1 and 0x4E00 <= ord(ch) <= 0x9FA5:
                chars.append(ch)
    return chars


def split_sparse_cmap_chars(chars):
    """按 LVGL SPARSE_TINY 的 uint16_t 偏移范围拆分有序字符。"""
    groups = []
    for ch in chars:
        if not groups or ord(ch) - ord(groups[-1][0]) > 0xFFFF:
            groups.append([])
        groups[-1].append(ch)
    return groups


def pack_bits(vals, bpp):
    """按 bpp 把像素值打包成字节流(MSB first,末尾补 0)——LVGL fmt_txt 位图格式。"""
    out = bytearray()
    acc = nbits = 0
    for v in vals:
        acc = (acc << bpp) | (v & ((1 << bpp) - 1))
        nbits += bpp
        while nbits >= 8:
            nbits -= 8
            out.append((acc >> nbits) & 0xFF)
    if nbits:
        out.append((acc << (8 - nbits)) & 0xFF)
    return bytes(out)


def render_glyph(font, ch, ascent, bpp):
    """渲染一个字形,返回 (bitmap_bytes, box_w, box_h, ofs_x, ofs_y, adv_w)。"""
    adv_w = int(round(font.getlength(ch) * 16))       # LVGL adv_w 单位 = 1/16 px
    bbox = font.getbbox(ch)
    if bbox is None:
        return b"", 0, 0, 0, 0, adv_w
    x0, y0, x1, y1 = bbox
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:                              # 空格等无墨迹字形
        return b"", 0, 0, 0, 0, adv_w

    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
    shift = 8 - bpp
    vals = [p >> shift for p in img.getdata()]        # 255→3 (2bpp)
    return pack_bits(vals, bpp), w, h, x0, ascent - y1, adv_w


def gen(size, out_path, font_name, extra_chars=None):
    font = ImageFont.truetype(FONT_PATH, size)
    ascent, descent = font.getmetrics()

    ascii_chars = [chr(c) for c in range(0x20, 0x7F)]         # 95 个
    if extra_chars is None:
        cjk_chars = gb2312_hanzi()
        for ch in COMMON_SYMBOLS:
            if ch not in cjk_chars:
                cjk_chars.append(ch)
        charset_note = f"GB2312 一级汉字/常用标点({len(cjk_chars)} 字)"
    else:
        cjk_chars = sorted(set(extra_chars), key=ord)
        charset_note = f"指定字符({len(cjk_chars)} 字):{''.join(cjk_chars)}"
    cjk_chars.sort(key=ord)
    all_chars = ascii_chars + cjk_chars

    bitmap = bytearray()
    dscs = [(0, 0, 0, 0, 0, 0)]                                # id 0 保留
    for ch in all_chars:
        bm, bw, bh, ox, oy, aw = render_glyph(font, ch, ascent, BPP)
        dscs.append((len(bitmap), aw, bw, bh, ox, oy))
        bitmap += bm

    cjk_groups = split_sparse_cmap_chars(cjk_chars)
    ascii_gid_start = 1

    lines = []
    lines.append('// Generated by tools/gen_cjk_font.py; do not edit manually.')
    lines.append('// Source Han Sans SC is licensed under the SIL Open Font License 1.1.')
    lines.append(f'// 字体:{os.path.basename(FONT_PATH)}  字号:{size}px  位深:{BPP}bpp')
    lines.append(f'// 字符集:ASCII(0x20-0x7E) + {charset_note}')
    lines.append('// 数据为 const,进 flash(.rodata),不占 DRAM。')
    lines.append('#include "lvgl.h"')
    lines.append('')
    lines.append(f'#if {font_name.upper()}_ENABLE || 1')
    lines.append('')
    lines.append('static const uint8_t glyph_bitmap[] = {')
    for i in range(0, len(bitmap), 16):
        lines.append('    ' + ''.join(f'0x{b:02X},' for b in bitmap[i:i + 16]))
    lines.append('};')
    lines.append('')
    lines.append('static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {')
    for (bi, aw, bw, bh, ox, oy) in dscs:
        lines.append(f'    {{.bitmap_index = {bi}, .adv_w = {aw}, .box_w = {bw}, '
                     f'.box_h = {bh}, .ofs_x = {ox}, .ofs_y = {oy}}},')
    lines.append('};')
    lines.append('')
    lines.append('/*码位稀疏；按 uint16_t 偏移上限拆分 cmap。*/')
    for group_index, group in enumerate(cjk_groups):
        if len(group) == 1:
            continue
        group_start = ord(group[0])
        offs = [ord(ch) - group_start for ch in group]
        lines.append(f'static const uint16_t unicode_list_cjk_{group_index}[] = {{')
        for i in range(0, len(offs), 12):
            lines.append('    ' + ''.join(f'0x{o:04X}, ' for o in offs[i:i + 12]).rstrip())
        lines.append('};')
        lines.append('')
    lines.append('static const lv_font_fmt_txt_cmap_t cmaps[] = {')
    lines.append('    {')
    lines.append(f'        .range_start = 32, .range_length = {len(ascii_chars)}, '
                 f'.glyph_id_start = {ascii_gid_start},')
    lines.append('        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,')
    lines.append('        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY')
    lines.append('    },')
    cjk_gid_start = 1 + len(ascii_chars)
    for group_index, group in enumerate(cjk_groups):
        group_start = ord(group[0])
        group_end = ord(group[-1])
        lines.append('    {')
        lines.append(f'        .range_start = {group_start}, .range_length = {group_end - group_start + 1}, '
                     f'.glyph_id_start = {cjk_gid_start},')
        if len(group) == 1:
            lines.append('        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,')
            lines.append('        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY')
        else:
            lines.append(f'        .unicode_list = unicode_list_cjk_{group_index}, '
                         f'.glyph_id_ofs_list = NULL, .list_length = {len(group)},')
            lines.append('        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY')
        cjk_gid_start += len(group)
        lines.append('    },')
    lines.append('};')
    lines.append('')
    lines.append('static const lv_font_fmt_txt_dsc_t font_dsc = {')
    lines.append('    .glyph_bitmap = glyph_bitmap,')
    lines.append('    .glyph_dsc = glyph_dsc,')
    lines.append('    .cmaps = cmaps,')
    lines.append('    .kern_dsc = NULL,')
    lines.append('    .kern_scale = 0,')
    lines.append(f'    .cmap_num = {1 + len(cjk_groups)},')
    lines.append(f'    .bpp = {BPP},')
    lines.append('    .kern_classes = 0,')
    lines.append('    .bitmap_format = 0,')
    lines.append('};')
    lines.append('')
    lines.append(f'const lv_font_t {font_name} = {{')
    lines.append('    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,')
    lines.append('    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,')
    lines.append(f'    .line_height = {ascent + descent},')
    lines.append(f'    .base_line = {descent},')
    lines.append('    .subpx = LV_FONT_SUBPX_NONE,')
    lines.append('    .underline_position = -2,')
    lines.append('    .underline_thickness = 1,')
    lines.append('    .dsc = &font_dsc,')
    lines.append('    .fallback = NULL,')
    lines.append('    .user_data = NULL,')
    lines.append('};')
    lines.append('')
    lines.append('#endif')
    lines.append('')

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"生成 {os.path.normpath(out_path)}  字形={len(dscs)-1} "
          f"位图={len(bitmap)/1024:.1f}KB 行高={ascent+descent} 基线={descent}")


def main():
    global FONT_PATH
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=FONT_PATH,
                    help="Path to SourceHanSansSC-Regular.otf (or another OFL-compatible font)")
    ap.add_argument("--size", type=int, action="append", help="字号(可多次);默认 16 和 22")
    ap.add_argument("--chars", help="只生成 ASCII + 这些字符(精简字体)")
    ap.add_argument("--name", help="输出字体变量名/文件名;默认 lv_font_cn_<size>")
    args = ap.parse_args()
    FONT_PATH = args.font
    sizes = args.size or [16, 22]
    if args.name and len(sizes) != 1:
        sys.exit("--name 只能配合一个 --size 使用")
    if not os.path.exists(FONT_PATH):
        sys.exit(f"找不到字体文件: {FONT_PATH}")
    os.makedirs(OUT_DIR, exist_ok=True)
    for s in sizes:
        name = args.name or f"lv_font_cn_{s}"
        gen(s, os.path.join(OUT_DIR, f"{name}.c"), name, args.chars)


if __name__ == "__main__":
    main()
