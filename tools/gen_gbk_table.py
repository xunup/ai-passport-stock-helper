#!/usr/bin/env python3
"""Generate the GB2312/GBK two-byte lookup table used for Sina stock names.

Sina responds with GBK-encoded display names.  The firmware only needs the
GB2312 rows (symbol rows A1-A9 and hanzi rows B0-F7); four-byte GB18030
sequences are not used by the quote feed.  Regenerate with:

    python3 tools/gen_gbk_table.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_C = ROOT / "main" / "gbk_table.c"
OUT_H = ROOT / "main" / "gbk_table.h"

ROW_START = 0xA1
ROW_END = 0xF7
COL_START = 0xA1
COL_END = 0xFE


def decode(hi: int, lo: int) -> int:
    try:
        text = bytes((hi, lo)).decode("gb18030")
    except UnicodeDecodeError:
        return 0
    if len(text) != 1:
        return 0
    code = ord(text)
    if code > 0xFFFF or 0xD800 <= code <= 0xDFFF or code == 0xFFFD:
        return 0
    return code


def main() -> None:
    rows = ROW_END - ROW_START + 1
    cols = COL_END - COL_START + 1
    table = []
    for hi in range(ROW_START, ROW_END + 1):
        table.append([decode(hi, lo) for lo in range(COL_START, COL_END + 1)])

    lines = [
        "// Generated by tools/gen_gbk_table.py; do not edit manually.",
        "// Maps GB2312/GBK two-byte codes (rows A1-F7, columns A1-FE) to BMP code points.",
        "// 0 means the byte pair is not a valid GB18030 character.",
        '#include "gbk_table.h"',
        "",
        "static const uint16_t s_gbk_table[%d][%d] = {" % (rows, cols),
    ]
    for hi, row in zip(range(ROW_START, ROW_END + 1), table):
        cells = ",".join("0x%04X" % value for value in row)
        lines.append("    { /* 0x%02X */ %s }," % (hi, cells))
    lines += [
        "};",
        "",
        "uint16_t gbk_gb2312_to_unicode(uint8_t hi, uint8_t lo)",
        "{",
        "    if (hi < 0x%02X || hi > 0x%02X || lo < 0x%02X || lo > 0x%02X) {" % (
            ROW_START, ROW_END, COL_START, COL_END),
        "        return 0;",
        "    }",
        "    return s_gbk_table[hi - 0x%02X][lo - 0x%02X];" % (ROW_START, COL_START),
        "}",
        "",
    ]
    OUT_C.write_text("\n".join(lines), encoding="utf-8")
    OUT_H.write_text(
        "// Generated alongside main/gbk_table.c by tools/gen_gbk_table.py.\n"
        "#pragma once\n\n"
        "#include <stdint.h>\n\n"
        "// Returns the BMP code point for a GB2312/GBK byte pair, or 0 if invalid.\n"
        "uint16_t gbk_gb2312_to_unicode(uint8_t hi, uint8_t lo);\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT_C} ({rows}x{cols} entries) and {OUT_H}")


if __name__ == "__main__":
    main()
